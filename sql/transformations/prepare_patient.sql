-- Prepare patient records for the current load; preserve original RAW_* values.
-- Parameter: LOAD_RUN_ID. Run once in the pipeline session before categorization.
-- Blank optional values become NULL; supplied invalid typed values are flagged.
CREATE TEMPORARY TABLE CLEANSTAR.RAW.PREPARED_PATIENT AS
WITH NORMALIZED AS (
    SELECT
        PATIENT_ID AS RAW_PATIENT_ID,
        BIRTHDATE AS RAW_BIRTHDATE,
        FIRST_NAME AS RAW_FIRST_NAME,
        MIDDLE_INITIAL AS RAW_MIDDLE_INITIAL,
        LAST_NAME AS RAW_LAST_NAME,
        SUFFIX AS RAW_SUFFIX,
        GENDER AS RAW_GENDER,
        ADDRESS AS RAW_ADDRESS,
        CITY AS RAW_CITY,
        STATE AS RAW_STATE,
        ZIP AS RAW_ZIP,
        PHONE AS RAW_PHONE,
        PAYER_ID AS RAW_PAYER_ID,
        INSURANCE_PLAN_NAME AS RAW_INSURANCE_PLAN_NAME,
        MEMBER_ID AS RAW_MEMBER_ID,
        GROUP_NUMBER AS RAW_GROUP_NUMBER,
        RELATIONSHIP_TO_INSURED AS RAW_RELATIONSHIP_TO_INSURED,
        COVERAGE_START_DATE AS RAW_COVERAGE_START_DATE,
        COVERAGE_END_DATE AS RAW_COVERAGE_END_DATE,
        COVERAGE_STATUS AS RAW_COVERAGE_STATUS,
        NULLIF(TRIM(PATIENT_ID), '') AS PATIENT_ID_TEXT,
        NULLIF(TRIM(BIRTHDATE), '') AS BIRTHDATE_TEXT,
        NULLIF(TRIM(FIRST_NAME), '') AS FIRST_NAME_TEXT,
        NULLIF(TRIM(MIDDLE_INITIAL), '') AS MIDDLE_INITIAL_TEXT,
        NULLIF(TRIM(LAST_NAME), '') AS LAST_NAME_TEXT,
        NULLIF(TRIM(SUFFIX), '') AS SUFFIX_TEXT,
        UPPER(NULLIF(TRIM(GENDER), '')) AS GENDER_TEXT,
        NULLIF(TRIM(ADDRESS), '') AS ADDRESS_TEXT,
        NULLIF(TRIM(CITY), '') AS CITY_TEXT,
        UPPER(NULLIF(TRIM(STATE), '')) AS STATE_TEXT,
        NULLIF(TRIM(ZIP), '') AS ZIP_TEXT,
        NULLIF(TRIM(PHONE), '') AS PHONE_TEXT,
        NULLIF(TRIM(PAYER_ID), '') AS PAYER_ID_TEXT,
        NULLIF(TRIM(INSURANCE_PLAN_NAME), '') AS INSURANCE_PLAN_NAME_TEXT,
        NULLIF(TRIM(MEMBER_ID), '') AS MEMBER_ID_TEXT,
        NULLIF(TRIM(GROUP_NUMBER), '') AS GROUP_NUMBER_TEXT,
        UPPER(NULLIF(TRIM(RELATIONSHIP_TO_INSURED), '')) AS RELATIONSHIP_TO_INSURED_TEXT,
        NULLIF(TRIM(COVERAGE_START_DATE), '') AS COVERAGE_START_DATE_TEXT,
        NULLIF(TRIM(COVERAGE_END_DATE), '') AS COVERAGE_END_DATE_TEXT,
        UPPER(NULLIF(TRIM(COVERAGE_STATUS), '')) AS COVERAGE_STATUS_TEXT,
        LOAD_RUN_ID,
        SOURCE_FILE,
        INGESTED_AT,
        HASH(PATIENT_ID, BIRTHDATE, FIRST_NAME, MIDDLE_INITIAL, LAST_NAME, SUFFIX, GENDER, ADDRESS, CITY, STATE, ZIP, PHONE, PAYER_ID, INSURANCE_PLAN_NAME, MEMBER_ID, GROUP_NUMBER, RELATIONSHIP_TO_INSURED, COVERAGE_START_DATE, COVERAGE_END_DATE, COVERAGE_STATUS) AS SOURCE_ROW_HASH
    FROM CLEANSTAR.RAW.PATIENT_INFO_RAW
    WHERE LOAD_RUN_ID = %s
),
CONVERTED AS (
    SELECT
        NORMALIZED.*,
        PATIENT_ID_TEXT AS PATIENT_ID,
        TRY_TO_DATE(BIRTHDATE_TEXT, 'YYYY-MM-DD') AS BIRTHDATE,
        FIRST_NAME_TEXT AS FIRST_NAME,
        MIDDLE_INITIAL_TEXT AS MIDDLE_INITIAL,
        LAST_NAME_TEXT AS LAST_NAME,
        SUFFIX_TEXT AS SUFFIX,
        GENDER_TEXT AS GENDER,
        ADDRESS_TEXT AS ADDRESS,
        CITY_TEXT AS CITY,
        STATE_TEXT AS STATE,
        ZIP_TEXT AS ZIP,
        PHONE_TEXT AS PHONE,
        PAYER_ID_TEXT AS PAYER_ID,
        INSURANCE_PLAN_NAME_TEXT AS INSURANCE_PLAN_NAME,
        MEMBER_ID_TEXT AS MEMBER_ID,
        GROUP_NUMBER_TEXT AS GROUP_NUMBER,
        RELATIONSHIP_TO_INSURED_TEXT AS RELATIONSHIP_TO_INSURED,
        TRY_TO_DATE(COVERAGE_START_DATE_TEXT, 'YYYY-MM-DD') AS COVERAGE_START_DATE,
        TRY_TO_DATE(COVERAGE_END_DATE_TEXT, 'YYYY-MM-DD') AS COVERAGE_END_DATE,
        COVERAGE_STATUS_TEXT AS COVERAGE_STATUS
    FROM NORMALIZED
)
SELECT
    RAW_PATIENT_ID,
    RAW_BIRTHDATE,
    RAW_FIRST_NAME,
    RAW_MIDDLE_INITIAL,
    RAW_LAST_NAME,
    RAW_SUFFIX,
    RAW_GENDER,
    RAW_ADDRESS,
    RAW_CITY,
    RAW_STATE,
    RAW_ZIP,
    RAW_PHONE,
    RAW_PAYER_ID,
    RAW_INSURANCE_PLAN_NAME,
    RAW_MEMBER_ID,
    RAW_GROUP_NUMBER,
    RAW_RELATIONSHIP_TO_INSURED,
    RAW_COVERAGE_START_DATE,
    RAW_COVERAGE_END_DATE,
    RAW_COVERAGE_STATUS,
    PATIENT_ID,
    BIRTHDATE,
    FIRST_NAME,
    MIDDLE_INITIAL,
    LAST_NAME,
    SUFFIX,
    GENDER,
    ADDRESS,
    CITY,
    STATE,
    ZIP,
    PHONE,
    PAYER_ID,
    INSURANCE_PLAN_NAME,
    MEMBER_ID,
    GROUP_NUMBER,
    RELATIONSHIP_TO_INSURED,
    COVERAGE_START_DATE,
    COVERAGE_END_DATE,
    COVERAGE_STATUS,
    LOAD_RUN_ID,
    SOURCE_FILE,
    INGESTED_AT,
    SOURCE_ROW_HASH,
    (BIRTHDATE_TEXT IS NOT NULL AND BIRTHDATE IS NULL) AS BIRTHDATE_CONVERSION_FAILED,
    (COVERAGE_START_DATE_TEXT IS NOT NULL AND COVERAGE_START_DATE IS NULL) AS COVERAGE_START_DATE_CONVERSION_FAILED,
    (COVERAGE_END_DATE_TEXT IS NOT NULL AND COVERAGE_END_DATE IS NULL) AS COVERAGE_END_DATE_CONVERSION_FAILED
FROM CONVERTED;
